"""Run training runs on Kaggle GPU kernels and bring their maps back (instead of / next to Colab).

A Kaggle GPU session has two T4s, so one kernel trains up to two runs at once, one per GPU, then
writes their TTA maps (or detections) exactly like the Colab notebook does. Runs are the names in the
EXPERIMENTS dict of colab/train_unet.ipynb, so both paths share one experiment list.

  python scripts/kaggle_gpu.py push-code                      # code bundle -> private dataset <owner>/filseg-code
  python scripts/kaggle_gpu.py push effb4_s1024_f0 effb4_v2_s1024_f0   # one kernel, both runs in parallel
  python scripts/kaggle_gpu.py status
  python scripts/kaggle_gpu.py fetch <kernel>                  # outputs/colab/<run>/ + LOCAL marker
  python scripts/kaggle_gpu.py daemon --extra "--bs 4" --kernel n1-f0f1=effb4_s1024_f0,effb4_s1024_f1 ...
      # pushes the kernels in order whenever a GPU session is free (every 10 min), fetches each one that
      # finishes; logs to outputs/kaggle_gpu.log

After fetch, scripts/watch_colab.py (with the run names in --runs) picks the runs up from the LOCAL
marker as if they were local maps. Kernels are private; nothing is submitted from them.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OWNER = "nguyenchicuong"
COMPETITION = "filament-segmentation-2026"
CODE_SLUG = "filseg-code"
BUILD = ROOT / "build" / "kaggle"
STATE = ROOT / "outputs" / "kaggle_gpu.json"

KERNEL_SCRIPT = r'''
# Generated by scripts/kaggle_gpu.py: trains RUNS (one per GPU, in parallel), then writes their maps.
import glob, json, os, shutil, subprocess, sys, tarfile, time, zipfile
RUNS = __RUNS__
W = "/kaggle/working"
CODE = "/tmp/filseg_code"
t0 = time.time()

def log(msg):
    print(f"[{(time.time() - t0) / 60:6.1f} min] {msg}", flush=True)

# Kaggle unpacks an uploaded zip, so the bundle arrives either as the zip or as its unpacked tree
bundle = glob.glob("/kaggle/input/**/filseg-colab.zip", recursive=True)
trees = [os.path.dirname(os.path.dirname(p)) for p in glob.glob("/kaggle/input/**/scripts/train_unet.py", recursive=True)]
data = [p for p in glob.glob("/kaggle/input/**/MAGFiLO_1.0_Kaggle_2026", recursive=True) if os.path.isdir(p)]
assert (bundle or trees) and data, (bundle, trees, data)
shutil.rmtree(CODE, ignore_errors=True)
if bundle:
    zipfile.ZipFile(bundle[0]).extractall(CODE)
else:
    shutil.copytree(trees[0], CODE)
os.makedirs(f"{CODE}/data", exist_ok=True)
os.symlink(data[0], f"{CODE}/data/MAGFiLO_1.0_Kaggle_2026")
os.chdir(CODE)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "segmentation-models-pytorch==0.5.0"], check=True)
subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv"])
log(f"code {(bundle or trees)[0]}, data {data[0]}")

def run_one(i, name, args, gpu):
    out = f"{W}/{name}"
    os.makedirs(out, exist_ok=True)
    env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu))
    detector = name.startswith("mrcnn")
    train = "scripts/train_maskrcnn.py" if detector else "scripts/train_unet.py"
    cmds = [[sys.executable, "-u", train, *args.split(), "--name", name, "--out-dir", out, "--workers", "2"]]
    ckpt = f"{out}/{name}.pt"
    held = "fold" if "--fold" in args.split() else "val"
    if detector:
        for which, d in (("test", "dets_test"), (held, "dets_val")):
            cmds.append([sys.executable, "-u", "scripts/infer_detections.py", "--ckpt", ckpt, "--which", which,
                         "--out", f"{out}/{d}"])
    else:
        for which, d in (("test", "probs_test"), (held, "probs_val")):
            cmds.append([sys.executable, "-u", "scripts/infer_probs.py", "--ckpt", ckpt, "--which", which, "--tta",
                         "--out", f"{out}/{d}"])
    return out, cmds, env

jobs = [run_one(i, n, a, i % 2) for i, (n, a) in enumerate(RUNS)]
# each GPU runs its own chain of commands; the two chains run at the same time
procs = []
for out, cmds, env in jobs:
    script = " && ".join(" ".join(f"'{c}'" for c in cmd) for cmd in cmds)
    logf = open(f"{out}/run.log", "w")
    procs.append((out, subprocess.Popen(["bash", "-c", script], stdout=logf, stderr=subprocess.STDOUT, env=env), logf))
    log(f"started {out}")
while any(p.poll() is None for _, p, _ in procs):
    time.sleep(300)
    for out, p, _ in procs:
        tail = open(f"{out}/run.log").read().splitlines()[-1:] if os.path.exists(f"{out}/run.log") else []
        log(f"{os.path.basename(out)}: {'running' if p.poll() is None else 'exit ' + str(p.returncode)} | {tail}")
status = {}
for out, p, logf in procs:
    logf.close()
    name = os.path.basename(out)
    status[name] = p.returncode
    for f in glob.glob(f"{out}/*.last.pt"):
        os.remove(f)  # resume state, ~3x the checkpoint; not needed once the run finished
    for d in glob.glob(f"{out}/probs_*") + glob.glob(f"{out}/dets_*"):
        with tarfile.open(d + ".tar", "w") as tf:
            tf.add(d, arcname=os.path.basename(d))
        shutil.rmtree(d)
json.dump(status, open(f"{W}/status.json", "w"))
log(f"done {status}")
'''


def sh(cmd: list, check: bool = True) -> subprocess.CompletedProcess:
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if check and r.returncode != 0:
        raise SystemExit(f"{' '.join(map(str, cmd))} failed:\n{r.stdout}\n{r.stderr}")
    return r


def experiments() -> dict[str, str]:
    nb = json.loads((ROOT / "colab" / "train_unet.ipynb").read_text())
    src = "".join(next(c["source"] for c in nb["cells"] if "EXPERIMENTS = {" in "".join(c["source"])))
    ns: dict = {}
    exec(src, ns)
    return ns["EXPERIMENTS"]


def load_state() -> dict:
    return json.loads(STATE.read_text()) if STATE.exists() else {"kernels": {}}


def save_state(st: dict) -> None:
    STATE.parent.mkdir(parents=True, exist_ok=True)
    STATE.write_text(json.dumps(st, indent=1))


def push_code() -> None:
    sh([sys.executable, ROOT / "scripts" / "package_colab.py"])
    d = BUILD / "code"
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir(parents=True)
    shutil.copy(ROOT / "build" / "colab" / "filseg-colab.zip", d / "filseg-colab.zip")
    ref = f"{OWNER}/{CODE_SLUG}"
    (d / "dataset-metadata.json").write_text(json.dumps({"title": CODE_SLUG, "id": ref,
                                                          "licenses": [{"name": "other"}]}))
    exists = sh(["kaggle", "datasets", "status", ref], check=False)
    if exists.returncode == 0 and "ready" in exists.stdout.lower():
        r = sh(["kaggle", "datasets", "version", "-p", d, "-m", time.strftime("%Y-%m-%d %H:%M")])
    else:
        r = sh(["kaggle", "datasets", "create", "-p", d])  # private by default
    print(r.stdout.strip()[-500:])
    for _ in range(60):  # a kernel pushed before the new version is ready would get the old code
        s = sh(["kaggle", "datasets", "status", ref], check=False).stdout.lower()
        if "ready" in s:
            print(f"{ref}: ready")
            return
        time.sleep(10)
    raise SystemExit(f"{ref} not ready after 10 minutes")


def push(runs: list[str], name: str | None, accelerator: str, extra: str = "") -> None:
    exps = experiments()
    missing = [r for r in runs if r not in exps]
    assert not missing, f"not in EXPERIMENTS: {missing}"
    assert 1 <= len(runs) <= 2, "one kernel trains one or two runs (two T4s)"
    slug = "filseg-gpu-" + (name or runs[0]).replace("_", "-")
    d = BUILD / slug
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir(parents=True)
    # extra arguments come last, so they override the EXPERIMENTS entry (argparse keeps the last value)
    (d / "run.py").write_text(KERNEL_SCRIPT.replace("__RUNS__", repr([(r, f"{exps[r]} {extra}".strip()) for r in runs])))
    (d / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{OWNER}/{slug}", "title": slug, "code_file": "run.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
        "dataset_sources": [f"{OWNER}/{CODE_SLUG}"], "competition_sources": [COMPETITION],
        "kernel_sources": [], "model_sources": []}, indent=1))
    r = sh(["kaggle", "kernels", "push", "-p", d, "--accelerator", accelerator])
    out = (r.stdout + r.stderr).strip()
    print(out[-500:])
    if "error" in out.lower():  # the CLI exits 0 when Kaggle refuses (e.g. both GPU sessions in use)
        raise SystemExit(f"push of {slug} refused")
    st = load_state()
    st["kernels"][slug] = {"runs": runs, "pushed": time.strftime("%Y-%m-%d %H:%M"), "accelerator": accelerator,
                           "extra": extra}
    save_state(st)


def status() -> None:
    st = load_state()
    for slug, k in st["kernels"].items():
        s = sh(["kaggle", "kernels", "status", f"{OWNER}/{slug}"], check=False)
        state = (s.stdout + s.stderr).strip().split('"')[-2] if '"' in s.stdout else (s.stdout + s.stderr).strip()
        k["status"] = state
        print(f"{slug:44s} {state:32s} {', '.join(k['runs'])}  (pushed {k['pushed']}{', fetched' if k.get('fetched') else ''})")
    save_state(st)


def fetch(slug: str) -> None:
    st = load_state()
    k = st["kernels"][slug]
    tmp = ROOT / "outputs" / "kaggle" / slug
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    sh(["kaggle", "kernels", "output", f"{OWNER}/{slug}", "-p", tmp])
    done = json.loads((tmp / "status.json").read_text()) if (tmp / "status.json").exists() else {}
    print(f"{slug}: exit codes {done}")
    for run in k["runs"]:
        src = tmp / run
        if done.get(run) != 0 or not src.is_dir():
            print(f"  {run}: FAILED, see {src / 'run.log'}")
            continue
        for t in [*src.glob("probs_*.tar"), *src.glob("dets_*.tar")]:
            with tarfile.open(t) as tf:
                tf.extractall(src, filter="data")
            t.unlink()
        dst = ROOT / "outputs" / "colab" / run
        if dst.exists():
            shutil.rmtree(dst)
        shutil.move(str(src), dst)
        (dst / "LOCAL").write_text(f"kaggle kernel {slug}\n")  # watch_colab.py: maps are already here
        print(f"  {run}: -> {dst}")
    k["fetched"] = True
    save_state(st)


def kernel_state(slug: str) -> str:
    s = sh(["kaggle", "kernels", "status", f"{OWNER}/{slug}"], check=False)
    out = s.stdout + s.stderr
    for state in ("COMPLETE", "ERROR", "CANCEL", "RUNNING", "QUEUED"):
        if state in out.upper():
            return state
    return "UNKNOWN"


def daemon(specs: list[str], extra: str, accelerator: str, poll: int) -> None:
    """specs: name=run1,run2 in priority order. Push each when a session is free, fetch when done."""
    queue = [(n, r.split(",")) for n, r in (x.split("=", 1) for x in specs)]
    logf = ROOT / "outputs" / "kaggle_gpu.log"

    def log(msg):
        with open(logf, "a") as fh:
            fh.write(f"[{time.strftime('%m-%d %H:%M')}] {msg}\n")

    log(f"daemon start: {queue} extra={extra!r}")
    while True:
        st = load_state()
        open_ = False
        for name, runs in queue:
            slug = "filseg-gpu-" + name.replace("_", "-")
            k = st["kernels"].get(slug)
            if k is None:
                open_ = True
                try:
                    push(runs, name, accelerator, extra)
                    log(f"{slug}: pushed {runs}")
                except SystemExit as e:
                    log(f"{slug}: not pushed ({e}); waiting for a free GPU session")
                    break  # keep the priority order
                st = load_state()
                continue
            if k.get("fetched"):
                continue
            open_ = True
            state = kernel_state(slug)
            if state in ("COMPLETE", "ERROR", "CANCEL"):
                try:
                    fetch(slug)
                    log(f"{slug}: {state}, fetched")
                except SystemExit as e:
                    log(f"{slug}: {state}, fetch failed: {e}")
                    k = load_state()["kernels"][slug]
                    k["fetched"] = "failed"
                    st2 = load_state(); st2["kernels"][slug] = k; save_state(st2)
                st = load_state()
        if not open_:
            log("daemon: every kernel fetched, exiting")
            return
        time.sleep(poll)


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("push-code")
    p = sub.add_parser("push")
    p.add_argument("runs", nargs="+")
    p.add_argument("--name", help="kernel name (default: the first run)")
    p.add_argument("--accelerator", default="NvidiaTeslaT4", help="T4 x2")
    p.add_argument("--extra", default="", help="arguments appended to every run, e.g. '--bs 4' for a 16 GB T4")
    sub.add_parser("status")
    f = sub.add_parser("fetch")
    f.add_argument("kernel")
    dm = sub.add_parser("daemon")
    dm.add_argument("--kernel", action="append", required=True, help="name=run1[,run2], in priority order")
    dm.add_argument("--extra", default="")
    dm.add_argument("--accelerator", default="NvidiaTeslaT4")
    dm.add_argument("--poll", type=int, default=600)
    a = ap.parse_args()
    if a.cmd == "push-code":
        push_code()
    elif a.cmd == "push":
        push(a.runs, a.name, a.accelerator, a.extra)
    elif a.cmd == "status":
        status()
    elif a.cmd == "daemon":
        daemon(a.kernel, a.extra, a.accelerator, a.poll)
    else:
        fetch(a.kernel)


if __name__ == "__main__":
    main()
